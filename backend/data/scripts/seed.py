async def seed(session: AsyncSession) -> None:
    existing_majors = await session.execute(select(Major))
    if existing_majors.scalars().first():
        print("数据库已有专业数据，跳过 seed。如需重新 seed，请先清空 majors 表。")
        return

    # Insert 18 assessment categories into majors table
    for code, name, disc, cat, desc, r, i, a, s, e, c in ASSESSMENT_CATEGORIES:
        session.add(Major(
            code=code, name=name, discipline_category=disc, major_category=cat,
            description=desc, riasec_r=r, riasec_i=i, riasec_a=a, riasec_s=s, riasec_e=e, riasec_c=c,
        ))

    await session.flush()
    print(f"✓ 插入 {len(ASSESSMENT_CATEGORIES)} 个测评大类")

    # Insert 93 专业类 into major_categories table
    for code, name, cat_code, cat_name, desc, reps in MAJOR_CATEGORIES:
        session.add(MajorCategory(
            code=code, name=name,
            assessment_category_code=cat_code, assessment_category_name=cat_name,
            description=desc, typical_representatives=reps,
        ))

    await session.flush()
    print(f"✓ 插入 {len(MAJOR_CATEGORIES)} 个专业类")


async def main() -> None:
    engine = create_async_engine(settings.DATABASE_URL)
    async_session = async_sessionmaker(engine, expire_on_commit=False)

    async with async_session() as session:
        async with session.begin():
            await seed(session)

    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(main())
